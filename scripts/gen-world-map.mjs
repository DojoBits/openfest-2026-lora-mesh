// Author-time generator for the slide „Различни ленти по света“ world map.
// Reads Natural Earth 1:110m countries (public domain, npm world-atlas),
// projects them equirectangular and writes static SVG path data to
// components/data/worldLand.ts. Run once: `node scripts/gen-world-map.mjs`.
// Nothing here runs at render time; the deck only imports the generated strings.
//
// Projection (linear, so the layout module can place callouts from lon/lat
// without d3): full 360° of longitude centred on 20°E (Pacific split at 160°W,
// Alaska's tip wraps to the right edge like on most world maps), latitude
// cropped to 72°N–50°S (only the Arctic, Svalbard and Antarctica fall outside it).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { geoEquirectangular, geoPath, geoCentroid } from 'd3-geo'
import { merge } from 'topojson-client'
import { filter, filterWeight, presimplify, simplify } from 'topojson-simplify'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
// Keep the file light (test budget 40 KB): Visvalingam simplification at
// MIN_AREA square degrees (about 1 px² on this map), and islands smaller than
// MIN_ISLAND square degrees are dropped; neither is visible from the hall.
const MIN_AREA = Number(process.env.MIN_AREA ?? 0.25)
const MIN_ISLAND = Number(process.env.MIN_ISLAND ?? 1.5)
const raw = JSON.parse(readFileSync(join(root, 'node_modules/world-atlas/countries-110m.json'), 'utf8'))
const pre = presimplify(raw)
const topo = filter(simplify(pre, MIN_AREA), filterWeight(pre, MIN_ISLAND))
const all = topo.objects.countries.geometries
const rawNames = raw.objects.countries.geometries.map(g => g.properties.name)

export const W = 880
export const LON0 = 20 // centre meridian
const LAT_N = 72
const LAT_S = -50
const K = W / 360 // px per degree
const H = Math.round((LAT_N - LAT_S) * K)
const LAT0 = (LAT_N + LAT_S) / 2

const rad = Math.PI / 180
const projection = geoEquirectangular()
  .rotate([-LON0, 0])
  .scale(K / rad)
  .translate([W / 2, H / 2 + (LAT0 * K)])
  .clipExtent([[0, 0], [W, H]])
// one decimal: the map renders at ~2x on a 1080p projector, so 0.1 px is plenty
const path = geoPath(projection).digits(1)

// Regions to highlight. Each is a merge of countries, so its outline is one path.
// Europe = EU27 + EEA + UK + CH + Western Balkans: where the ETSI EN 300 220
// 863–870 MHz band applies. Bulgaria is drawn on its own in the accent colour.
// Russia, Belarus, Ukraine, Turkey are left out on purpose (own rules / own
// Meshtastic codes such as RU, UA).
const EUROPE = [
  'Albania', 'Austria', 'Belgium', 'Bosnia and Herz.', 'Croatia', 'Cyprus', 'Czechia', 'Denmark',
  'Estonia', 'Finland', 'France', 'Germany', 'Greece', 'Hungary', 'Iceland', 'Ireland', 'Italy',
  'Kosovo', 'Latvia', 'Lithuania', 'Luxembourg', 'Macedonia', 'Montenegro', 'Netherlands', 'Norway',
  'Poland', 'Portugal', 'Romania', 'Serbia', 'Slovakia', 'Slovenia', 'Spain', 'Sweden',
  'Switzerland', 'United Kingdom',
]
const REGIONS = {
  EU: EUROPE,
  BG: ['Bulgaria'],
  US: ['United States of America'],
  ANZ: ['Australia', 'New Zealand'],
  JP: ['Japan'],
  KR: ['South Korea'],
  IN: ['India'],
  CN: ['China'],
}

const byName = names => all.filter(g => names.includes(g.properties.name))
for (const [k, names] of Object.entries(REGIONS)) {
  // checked against the unfiltered data: tiny countries (Luxembourg) may be dropped by MIN_ISLAND
  const missing = names.filter(n => !rawNames.includes(n))
  if (missing.length) throw new Error(`${k}: missing ${missing.join(', ')}`)
}

// Drop overseas parts that are not Europe (French Guiana sits in France's polygon).
const keepEurope = (geo) => {
  if (geo.type !== 'MultiPolygon') return geo
  const coordinates = geo.coordinates.filter(poly => geoCentroid({ type: 'Polygon', coordinates: poly })[0] > -30)
  return { ...geo, coordinates }
}

const land = merge(topo, all.filter(g => g.properties.name !== 'Antarctica'))
const out = { LAND: path(land) }
for (const [k, names] of Object.entries(REGIONS)) {
  let geo = merge(topo, byName(names))
  if (k === 'EU') geo = keepEurope(geo)
  out[k] = path(geo)
}

const body = `// GENERATED by scripts/gen-world-map.mjs from Natural Earth 1:110m countries
// (public domain, npm world-atlas). Do not edit by hand; re-run the script.
// Equirectangular, centre meridian ${LON0}°E, latitude ${LAT_N}°N–${-LAT_S}°S, ${W}×${H} px.
// Named worldLand (not after the component) to dodge the name-clash trap.

export const MAP_W = ${W}
export const MAP_H = ${H}
/** Projection constants: x = MAP_W / 2 + (lon − MAP_LON0) · MAP_K, y = (MAP_LAT_N − lat) · MAP_K. */
export const MAP_LON0 = ${LON0}
export const MAP_LAT_N = ${LAT_N}
export const MAP_K = ${K}

/** All land except Antarctica, merged into one outline. */
export const LAND_PATH = ${JSON.stringify(out.LAND)}

export type MapRegion = ${Object.keys(REGIONS).map(k => `'${k}'`).join(' | ')}

/** Highlighted regions, one merged outline each. */
export const REGION_PATHS: Readonly<Record<MapRegion, string>> = {
${Object.keys(REGIONS).map(k => `  ${k}: ${JSON.stringify(out[k])},`).join('\n')}
}
`
const file = join(root, 'components/data/worldLand.ts')
writeFileSync(file, body)
console.log(`wrote ${file}: ${body.length} bytes, ${W}x${H}`)
